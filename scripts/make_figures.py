"""Figures + reports/RESULTS.md from the measured JSON in reports/ (no new numbers)."""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import numpy as np  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
R = ROOT / "reports"
FIG = R / "figures"
SPLIT_NAMES = {"random": "Random windows (leaky)", "load3": "Train 0-2 hp -> test 3 hp",
               "lolo_mean": "Leave-one-load-out mean", "cross_size": "Unseen 14-mil faults"}
MODEL_NAMES = {"rf": "RandomForest (56 features)", "gbm": "HistGBM (56 features)", "cnn": "1D-CNN (raw window)"}


def cm_plot(run: dict, path: Path, title: str) -> None:
    m = np.asarray(run["confusion_matrix"], float)
    keep = m.sum(1) > 0
    rows = m / np.maximum(m.sum(1, keepdims=True), 1)
    cls = run["classes"]
    fig, ax = plt.subplots(figsize=(6.2, 5.4), dpi=110)
    ax.imshow(rows, cmap="Blues", vmin=0, vmax=1)
    for i in range(len(cls)):
        for j in range(len(cls)):
            if m[i, j] and keep[i]:
                ax.text(j, i, int(m[i, j]), ha="center", va="center", fontsize=8,
                        color="white" if rows[i, j] > 0.5 else "black")
    ax.set_xticks(range(len(cls)), cls, rotation=45, ha="right")
    ax.set_yticks(range(len(cls)), cls)
    ax.set_xlabel("predicted")
    ax.set_ylabel("true")
    ax.set_title(f"{title}\nacc {run['accuracy']:.3f} | macro-F1 {run['macro_f1']:.3f}", fontsize=10)
    fig.tight_layout()
    fig.savefig(path)
    plt.close(fig)


def main() -> None:
    FIG.mkdir(parents=True, exist_ok=True)
    metrics = json.loads((R / "metrics.json").read_text())
    runs = {p.stem: json.loads(p.read_text()) for p in (R / "runs").glob("*.json")}
    for key in ("10class_load3_cnn", "10class_load3_gbm", "10class_random_cnn", "4class_cross_size_cnn",
                "4class_cross_size_gbm", "4class_cross_size_rf"):
        if key in runs:
            t, s, m = key.split("_", 1)[0], key.split("_")[1] if "cross" not in key else "cross_size", key.split("_")[-1]
            cm_plot(runs[key], FIG / f"cm_{key}.png", f"{MODEL_NAMES[m]} | {t} | {SPLIT_NAMES[s]}")

    hi = json.loads((R / "health_index.json").read_text())
    by = hi["by_class_load3"]
    fig, ax = plt.subplots(figsize=(7, 3.4), dpi=110)
    names = list(by)
    ax.bar(names, [by[n]["mean_hi"] for n in names], color=["#3ddc97"] + ["#4c9bff"] * (len(names) - 1))
    ax.axhline(hi["threshold_served"], color="r", ls="--", label="alarm threshold (cross-load p99 of healthy 0-2 hp)")
    ax.set_yscale("log")
    ax.set_ylabel("mean health index (log)")
    ax.set_title(f"Health index on unseen 3 hp data - AUROC healthy vs fault {hi['auroc_normal_vs_fault_load3']:.3f}")
    ax.legend(fontsize=8)
    plt.xticks(rotation=30)
    fig.tight_layout()
    fig.savefig(FIG / "health_index_by_class.png")
    plt.close(fig)

    lines = ["# Measured results", "", "Generated by `scripts/make_figures.py` from `reports/metrics.json` "
             "(accuracy / macro-F1 on the test side of each split).", ""]
    for task in ("10class", "4class"):
        cols = ["random", "load3", "lolo_mean"] + (["cross_size"] if task == "4class" else [])
        lines += [f"## {task}", "", "| model | " + " | ".join(SPLIT_NAMES[c] for c in cols) + " |",
                  "|---|" + "---|" * len(cols)]
        for m in ("rf", "gbm", "cnn"):
            if m not in metrics.get(task, {}):
                continue
            cells = []
            for c in cols:
                r = metrics[task][m].get(c)
                cells.append(f"{r['accuracy']:.4f} / {r['macro_f1']:.4f}" if r else "n/a")
            lines.append(f"| {MODEL_NAMES[m]} | " + " | ".join(cells) + " |")
        lines.append("")
    lines += ["## Per-class recall, 4-class cross-size split (unseen 0.014\" faults)", "",
              "| model | " + " | ".join(runs["4class_cross_size_gbm"]["per_class_recall"]) + " |",
              "|---|" + "---|" * len(runs["4class_cross_size_gbm"]["per_class_recall"])]
    for m in ("rf", "gbm", "cnn"):
        r = runs.get(f"4class_cross_size_{m}")
        if r:
            lines.append(f"| {MODEL_NAMES[m]} | " + " | ".join(f"{v:.3f}" for v in r["per_class_recall"].values()) + " |")
    dep = json.loads((R / "deploy_model.json").read_text())
    lines += ["", "## Per-class recall, 10-class, train 0-2 hp -> test 3 hp (exported models)", "",
              "| model | " + " | ".join(dep["gbm"]["per_class_recall"]) + " |",
              "|---|" + "---|" * len(dep["gbm"]["per_class_recall"])]
    for k, nm in (("cnn_onnx", "1D-CNN (ONNX export)"), ("gbm", "HistGBM")):
        lines.append(f"| {nm} | " + " | ".join(f"{v:.3f}" for v in dep[k]["per_class_recall"].values()) + " |")
    (R / "RESULTS.md").write_text("\n".join(lines) + "\n")
    print("wrote figures and RESULTS.md")


if __name__ == "__main__":
    main()
